"""Builds the HyperFrames karaoke-captions composition (transparent overlay) from captions.json.

The caption data is inlined (compositions must not fetch), so re-run this after build_audio.py.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "hyperframes/captions")
data = json.load(open(os.path.join(DIR, "captions.json")))
dur = data["duration"]

html = f"""<!doctype html>
<html lang="ru" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="./assets/gsap.min.js"></script>
    <style>
      /* Generated by scripts/make_captions.py from captions.json — edit those, not this file. */
      @font-face {{ font-family: 'Oswald'; font-weight: 700; font-display: block; src: url(./assets/fonts/oswald-latin-700-normal.woff2) format('woff2'); unicode-range: U+0000-00FF, U+2000-206F; }}
      @font-face {{ font-family: 'Oswald'; font-weight: 700; font-display: block; src: url(./assets/fonts/oswald-cyrillic-700-normal.woff2) format('woff2'); unicode-range: U+0400-045F; }}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: transparent; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
      .line {{ position: absolute; left: 50px; right: 50px; top: 1560px; display: flex; flex-wrap: wrap; justify-content: center; gap: 6px 18px; opacity: 0; }}
      .w {{ position: relative; display: inline-block; font-family: 'Oswald', sans-serif; font-weight: 700; font-size: 74px; line-height: 1.08; text-transform: uppercase; color: #fff;
            padding: 0 12px; border-radius: 14px; isolation: isolate;
            -webkit-text-stroke: 3px #141414; paint-order: stroke fill; text-shadow: 0 6px 18px rgba(0,0,0,0.45); }}
      .w .bg {{ position: absolute; inset: 4px 0 2px; border-radius: 14px; background: #E4FF3A; z-index: -1; transform: scale(0); }}
      .w.kw {{ color: #E4FF3A; }}
      .w.kw .bg {{ background: #6C2BFF; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{dur}" data-width="1080" data-height="1920">
      <div id="caps" class="clip" data-start="0" data-duration="{dur}" data-track-index="0"></div>
    </div>
    <script>
      const CAPS = {json.dumps(data["lines"], ensure_ascii=False)};
      const root = document.getElementById('caps');
      CAPS.forEach((ln, i) => {{
        const el = document.createElement('div');
        el.className = 'line';
        el.id = 'l' + i;
        ln.words.forEach((w, j) => {{
          const s = document.createElement('span');
          s.className = 'w' + (w.hl ? ' kw' : '');
          s.id = 'l' + i + 'w' + j;
          s.innerHTML = '<span class="bg"></span>' + w.w.replace(/</g, '&lt;');
          el.appendChild(s);
        }});
        root.appendChild(el);
      }});

      const tl = gsap.timeline({{ paused: true }});
      CAPS.forEach((ln, i) => {{
        const el = '#l' + i;
        tl.fromTo(el, {{ opacity: 0, y: 40, scale: 0.92 }}, {{ opacity: 1, y: 0, scale: 1, duration: 0.18, ease: 'back.out(2)' }}, ln.start);
        tl.to(el, {{ opacity: 0, y: -20, duration: 0.12, ease: 'power2.in' }}, Math.max(ln.start + 0.2, ln.end - 0.12));
        ln.words.forEach((w, j) => {{
          const id = '#l' + i + 'w' + j;
          const next = j + 1 < ln.words.length ? ln.words[j + 1].t : ln.end;
          const on = Math.max(0.12, Math.min(next - w.t, 0.9));
          tl.fromTo(id + ' .bg', {{ scale: 0 }}, {{ scale: 1, duration: 0.08, ease: 'power2.out', immediateRender: false }}, w.t);
          tl.fromTo(id, {{ y: 0 }}, {{ y: -8, duration: 0.08, yoyo: true, repeat: 1, ease: 'power2.out', immediateRender: false }}, w.t);
          tl.fromTo(id, {{ color: w.hl ? '#E4FF3A' : '#ffffff' }}, {{ color: w.hl ? '#ffffff' : '#141414', duration: 0.06, immediateRender: false }}, w.t);
          if (!w.hl) {{
            tl.to(id + ' .bg', {{ scale: 0, duration: 0.08 }}, w.t + on);
            tl.to(id, {{ color: '#ffffff', duration: 0.06 }}, w.t + on);
          }}
        }});
      }});
      window.__timelines = window.__timelines || {{}};
      window.__timelines['main'] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
"""
open(os.path.join(DIR, "index.html"), "w").write(html)
print("lines:", len(data["lines"]), "duration:", dur)
