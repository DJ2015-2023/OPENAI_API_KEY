import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, "src/timing.json")))
sc = T["scenes"]["venue"]
dur = round(sc["dur"] / T["fps"], 3)
w = [round((fr - sc["from"]) / T["fps"], 3) for _, fr in T["words"]["s05"]]


def rnd(i):
    x = math.sin(i * 12.9898 + 78.233) * 43758.5453
    return x - math.floor(x)


