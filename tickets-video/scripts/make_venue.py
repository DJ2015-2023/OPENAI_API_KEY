    ang = rnd(i + 80) * math.pi
    L = 140 + rnd(i + 120) * 220
    streets.append(f"M {x0:.0f} {y0:.0f} L {x0 + math.cos(ang) * L:.0f} {y0 + math.sin(ang) * L:.0f}")
