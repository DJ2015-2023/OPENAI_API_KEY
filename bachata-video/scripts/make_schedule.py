"""HyperFrames schedule overlay (transparent background): header + four date cards that land on the
beat, the last one (video shoot) highlighted. Beat times come from src/timing.json and are inlined.
Rendered with `--format mov` (ProRes 4444 + alpha) and composited by Remotion over the footage.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, "src/timing.json")))
sc = T["sections"]["schedule"]
dur = round(sc["dur"] / T["fps"], 3)
beats = [round((T["beats"][sc["beat0"] + i] - sc["from"]) / T["fps"], 3) for i in range(20)]

CARDS = [
    ("14", "НОЯБРЯ", "СУББОТА", "14:00–16:00", False),
    ("16", "НОЯБРЯ", "ПОНЕДЕЛЬНИК", "20:00–22:00", False),
    ("21", "НОЯБРЯ", "СУББОТА", "14:00–16:00", False),
    ("22", "НОЯБРЯ", "ВОСКРЕСЕНЬЕ", "Вечерняя видеосъёмка", True),
]
fonts = "\n".join(
    f"      @font-face {{ font-family: '{fam}'; font-weight: {w}; font-style: {st}; font-display: block; src: url(./assets/fonts/{file}-{sub}-{w}-{st}.woff2) format('woff2'); unicode-range: {rng}; }}"
    for fam, file, w, st in [("Montserrat", "montserrat", 500, "normal"), ("Montserrat", "montserrat", 700, "normal"), ("Montserrat", "montserrat", 800, "normal"),
                             ("Cormorant Garamond", "cormorant-garamond", 600, "italic"), ("Great Vibes", "great-vibes", 400, "normal")]
    for sub, rng in (("latin", "U+0000-00FF, U+2000-206F"), ("cyrillic", "U+0400-045F"))
)
cards = "\n".join(
    f"""        <div class="card{' hero' if hero else ''}" id="c{i}">
          <div class="date"><div class="d">{d}</div><div class="m">{m}</div></div>
          <div class="info"><div class="wd">{wd}</div><div class="tm">{tm}</div></div>
          {'<svg class="cam" viewBox="0 0 24 24"><rect x="2.5" y="6.5" width="14" height="11" rx="2"/><path d="M16.5 10l5-3v10l-5-3"/></svg>' if hero else '<div class="dot"></div>'}
        </div>"""
    for i, (d, m, wd, tm, hero) in enumerate(CARDS)
)

html = f"""<!doctype html>
<html lang="ru" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="./assets/gsap.min.js"></script>
    <style>
      /* Generated by scripts/make_schedule.py — edit that, not this file. */
{fonts}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: transparent; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
      .head {{ position: absolute; top: 250px; left: 0; right: 0; text-align: center; }}
      .eyebrow {{ font-family: 'Montserrat'; font-weight: 500; font-size: 34px; letter-spacing: 0.32em; padding-left: 0.32em; color: #F4B6C2; }}
      .title {{ font-family: 'Montserrat'; font-weight: 800; font-size: 118px; line-height: 1; margin-top: 14px;
        background: linear-gradient(180deg, #FFF1E6 0%, #F2C9B0 35%, #C98E73 60%, #FBE0CF 100%); -webkit-background-clip: text; background-clip: text; color: transparent; }}
      .script {{ font-family: 'Great Vibes'; font-size: 120px; color: #FADADD; margin-top: -20px; text-shadow: 0 0 30px rgba(255,140,170,0.55); }}
      .rule {{ width: 520px; height: 2px; margin: 18px auto 0; background: linear-gradient(90deg, transparent, #F2C9B0, transparent); }}
      .list {{ position: absolute; left: 70px; right: 70px; top: 980px; display: flex; flex-direction: column; gap: 28px; }}
      .card {{ display: flex; align-items: center; gap: 36px; padding: 26px 40px; border-radius: 34px;
        background: linear-gradient(160deg, rgba(60,14,32,0.72), rgba(14,4,9,0.72)); border: 1.5px solid rgba(255,205,215,0.42);
        box-shadow: 0 24px 60px rgba(0,0,0,0.45), inset 0 1px 0 rgba(255,255,255,0.16); }}
      .card.hero {{ border: 2.5px solid #F2C9B0; box-shadow: 0 0 50px rgba(255,140,170,0.55), 0 24px 60px rgba(0,0,0,0.45); background: linear-gradient(160deg, rgba(120,20,55,0.8), rgba(30,6,16,0.8)); }}
      .date {{ width: 170px; text-align: center; border-right: 2px solid rgba(255,205,215,0.35); padding-right: 30px; }}
      .d {{ font-family: 'Montserrat'; font-weight: 800; font-size: 100px; line-height: 0.95;
        background: linear-gradient(180deg, #FFF1E6 0%, #F2C9B0 35%, #C98E73 60%, #FBE0CF 100%); -webkit-background-clip: text; background-clip: text; color: transparent; }}
      .m {{ font-family: 'Montserrat'; font-weight: 700; font-size: 26px; letter-spacing: 0.2em; color: #F4B6C2; }}
      .info {{ flex: 1; }}
      .wd {{ font-family: 'Montserrat'; font-weight: 700; font-size: 34px; letter-spacing: 0.14em; color: #F4B6C2; }}
      .tm {{ font-family: 'Montserrat'; font-weight: 800; font-size: 64px; color: #FFF4EE; margin-top: 4px; }}
      .hero .tm {{ font-family: 'Cormorant Garamond'; font-style: italic; font-weight: 600; font-size: 60px; line-height: 1.05; }}
      .dot {{ width: 22px; height: 22px; border-radius: 50%; background: #F4B6C2; box-shadow: 0 0 18px #F4B6C2; }}
      .cam {{ width: 84px; height: 84px; fill: none; stroke: #F2C9B0; stroke-width: 1.6; stroke-linecap: round; stroke-linejoin: round; filter: drop-shadow(0 0 10px rgba(255,170,190,0.7)); }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{dur}" data-width="1080" data-height="1920">
      <div id="scene" class="clip" data-start="0" data-duration="{dur}" data-track-index="0">
        <div class="head" id="head">
          <div class="eyebrow" id="eb">РАСПИСАНИЕ КУРСА</div>
          <div class="script" id="sc">ноябрь</div>
          <div class="rule" id="rule"></div>
        </div>
        <div class="list">
{cards}
        </div>
      </div>
    </div>
    <script>
      const B = {json.dumps(beats)};
      const tl = gsap.timeline({{ paused: true }});
      tl.fromTo('#eb', {{ opacity: 0, y: -30, scaleX: 1.3 }}, {{ opacity: 1, y: 0, scaleX: 1, duration: 0.6, ease: 'power3.out' }}, 0.05);
      tl.fromTo('#sc', {{ opacity: 0, clipPath: 'inset(-20% 100% -20% -5%)' }}, {{ opacity: 1, clipPath: 'inset(-20% 0% -20% -5%)', duration: 0.8, ease: 'sine.inOut' }}, B[1]);
      tl.fromTo('#rule', {{ scaleX: 0 }}, {{ scaleX: 1, duration: 0.6, ease: 'power2.out' }}, B[1] + 0.3);
      [0, 1, 2, 3].forEach((i) => {{
        const at = B[2 + i * 4] - 0.12;
        tl.fromTo('#c' + i, {{ opacity: 0, x: i % 2 ? 260 : -260, rotation: i % 2 ? 4 : -4, scale: 0.9 }},
          {{ opacity: 1, x: 0, rotation: 0, scale: 1, duration: 0.55, ease: 'back.out(1.6)' }}, at);
        tl.fromTo('#c' + i + ' .d', {{ y: 40, opacity: 0 }}, {{ y: 0, opacity: 1, duration: 0.4, ease: 'power3.out' }}, at + 0.15);
      }});
      // the hero card (video shoot) breathes on the beat after it lands
      for (let k = 15; k < 20; k++) {{
        tl.fromTo('#c3', {{ scale: 1.035 }}, {{ scale: 1, duration: 0.4, ease: 'power2.out', immediateRender: false }}, B[k]);
      }}
      tl.to('#scene', {{ opacity: 0, y: -40, duration: 0.25, ease: 'power2.in' }}, {dur} - 0.3);
      window.__timelines = window.__timelines || {{}};
      window.__timelines['main'] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
"""
open(os.path.join(ROOT, "hyperframes/schedule/index.html"), "w").write(html)
print("schedule", dur, beats[:4])
